class FakeRunner:
    def __init__(self, profile, response_factory, *, barrier=False):
        self.profile = profile
        self.response_factory = response_factory
        self.barrier = threading.Barrier(len(AGENT_ROLES)) if barrier else None
        self.lock = threading.Lock()
        self.active = 0
        self.max_active = 0
        self.started = []

    def run(self, request, progress=None):
        with self.lock:
            self.started.append(request.role)
            self.active += 1
            self.max_active = max(self.max_active, self.active)
        try:
            if self.barrier is not None:
                self.barrier.wait(timeout=2)
            if progress is not None:
                progress(ProgressEvent(request.role, "output", "fake output"))
            return self.response_factory(request.role)
        finally:
            with self.lock:
                self.active -= 1


def _valid_response(root, profile, role):
    if role == "stack-detector":
        return json.dumps({"role": role, "profile": asdict(profile)})
    paths = [
        artifact.path
        for artifact in generate_artifacts(root, profile)
        if artifact.path in role_allowlist(role)
    ]
    return json.dumps(
        {
            "role": role,
            "artifacts": [
                {
                    "path": path,
                    "content": f"generated by {role}: {path}\n",
                    "reason": "test",
                }
                for path in paths
            ],
        }
    )


class OrchestrationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        (self.root / "app.py").write_text("print('ok')\n", encoding="utf-8")
        self.profile = detect_repository(self.root)

    def tearDown(self):
        self.temporary.cleanup()

    def test_exactly_four_roles_run_concurrently_and_emit_progress(self):
        events = []
        runner = FakeRunner(
            self.profile,
            lambda role: _valid_response(self.root, self.profile, role),
            barrier=True,
        )

        artifacts = orchestrate_generation(
            self.root,
            self.profile,
            runner=runner,
            timeout=1,
            progress=events.append,
        )

        self.assertEqual(set(runner.started), set(AGENT_ROLES))
        self.assertEqual(len(runner.started), 4)
        self.assertEqual(runner.max_active, 4)
        self.assertEqual(
            [artifact.path for artifact in artifacts],
            [
                "Dockerfile",
                "Makefile",
                ".python-version",
                "requirements.repro-doctor.txt",
                "README.repro-doctor.md",
            ],
        )
        self.assertEqual({event.role for event in events}, set(AGENT_ROLES))
        self.assertEqual(
            [event.kind for event in events[:4]],
            ["start", "start", "start", "start"],
        )
        self.assertTrue(any(event.kind == "output" for event in events))
        self.assertEqual(
            {event.role for event in events if event.kind == "complete"},
            set(AGENT_ROLES),
        )

    def test_malformed_unsafe_and_duplicate_output_is_rejected(self):
        cases = {
            "malformed": lambda role: "not JSON" if role == "dockerfile-writer" else _valid_response(self.root, self.profile, role),
            "unsafe": lambda role: (
                json.dumps(
                    {
                        "role": role,
                        "artifacts": [
                            {"path": "../Dockerfile", "content": "bad", "reason": "test"}
                        ],
                    }
                )
                if role == "dockerfile-writer"
                else _valid_response(self.root, self.profile, role)
            ),
            "duplicate": lambda role: (
                json.dumps(
                    {
                        "role": role,
                        "artifacts": [
                            {"path": "Dockerfile", "content": "one", "reason": "test"},
                            {"path": "Dockerfile", "content": "two", "reason": "test"},
                        ],
                    }
                )
                if role == "dockerfile-writer"
                else _valid_response(self.root, self.profile, role)
            ),
        }

        for label, response_factory in cases.items():
            with self.subTest(label=label):
                runner = FakeRunner(self.profile, response_factory, barrier=True)
                expected = (
                    AgentProtocolError
                    if label == "malformed"
                    else ArtifactValidationError
                )
                with self.assertRaises(expected):
                    orchestrate_generation(self.root, self.profile, runner=runner, timeout=1)

    def test_missing_required_artifacts_are_rejected(self):
        for missing_role in (
            "dockerfile-writer",
            "test-script-writer",
            "readme-writer",
        ):
            with self.subTest(role=missing_role):
                def response_factory(role, missing_role=missing_role):
                    if role == missing_role:
                        return json.dumps({"role": role, "artifacts": []})
                    return _valid_response(self.root, self.profile, role)

                runner = FakeRunner(self.profile, response_factory, barrier=True)
                with self.assertRaisesRegex(
                    AgentProtocolError,
                    f"{missing_role} omitted deterministic artifacts",
                ):
                    orchestrate_generation(
                        self.root,
                        self.profile,
                        runner=runner,
                        timeout=1,
                    )

    def test_writer_roles_may_noop_when_source_preserves_their_files(self):
        (self.root / "Dockerfile").write_text("FROM python:3.12-slim\n", encoding="utf-8")
        (self.root / "Makefile").write_text(
            ".PHONY: test\n\ntest:\n\tpython -m unittest\n",
            encoding="utf-8",
        )
        (self.root / ".python-version").write_text("3.12\n", encoding="utf-8")
        (self.root / "requirements.txt").write_text("requests==2.32.3\n", encoding="utf-8")
        profile = detect_repository(self.root)
        runner = FakeRunner(
            profile,
            lambda role: _valid_response(self.root, profile, role),
            barrier=True,
        )

        artifacts = orchestrate_generation(
            self.root,
            profile,
            runner=runner,
            timeout=1,
        )

        self.assertEqual([artifact.path for artifact in artifacts], ["README.repro-doctor.md"])

    def test_role_failure_is_reported_and_cancellation_is_attempted(self):
        events = []
        profile = self.profile
        root = self.root

        class FailingRunner(FakeRunner):
            def __init__(self):
                super().__init__(profile, lambda role: _valid_response(root, profile, role))
                self.cancelled = []
                self.stop = threading.Event()

            def run(self, request, progress=None):
                if request.role == "stack-detector":
                    raise RuntimeError("runner failed")
                with self.lock:
                    self.started.append(request.role)
                    self.active += 1
                    self.max_active = max(self.max_active, self.active)
                try:
                    self.stop.wait(10)
                    return _valid_response(root, profile, request.role)
                finally:
                    with self.lock:
                        self.active -= 1

            def cancel(self, request):
                self.cancelled.append(request.role)
                self.stop.set()

        runner = FailingRunner()
        with self.assertRaises(AgentError) as raised:
            orchestrate_generation(
                self.root,
                self.profile,
                runner=runner,
                timeout=1,
                progress=events.append,
            )

        self.assertIn("runner failed", str(raised.exception))
        self.assertIn("stack-detector", {event.role for event in events if event.kind == "failed"})
        self.assertTrue(set(runner.cancelled))

    def test_timeout_is_bounded_and_cancels_pending_roles(self):
        events = []
        profile = self.profile
        root = self.root

        class SlowRunner(FakeRunner):
            def __init__(self):
                super().__init__(profile, lambda role: _valid_response(root, profile, role))
                self.stop = threading.Event()
                self.cancelled = []

            def run(self, request, progress=None):
                if request.role == "readme-writer":
                    self.stop.wait(10)
                    return _valid_response(root, profile, request.role)
                return super().run(request, progress)

            def cancel(self, request):
                self.cancelled.append(request.role)
                self.stop.set()

        runner = SlowRunner()
        started = time.monotonic()
        with self.assertRaises(AgentTimeoutError):
            orchestrate_generation(
                self.root,
                self.profile,
                runner=runner,
                timeout=0.05,
                progress=events.append,
            )
        elapsed = time.monotonic() - started

        self.assertLess(elapsed, 1.0)
        self.assertIn("readme-writer", runner.cancelled)
        self.assertIn(
            "readme-writer",
            {event.role for event in events if event.kind == "timeout"},
        )

    def test_pipeline_agent_mode_materializes_fake_runner_output(self):
        before = (self.root / "app.py").read_bytes()
        with tempfile.TemporaryDirectory() as temporary:
            runner = FakeRunner(
                self.profile,
                lambda role: _valid_response(self.root, self.profile, role),
                barrier=True,
            )
            result = process_repository(
                str(self.root),
                Path(temporary) / "output",
                mode="agent",
                agent_runner=runner,
                agent_timeout=1,
            )

        self.assertEqual(before, (self.root / "app.py").read_bytes())
        self.assertIn("Dockerfile", result.changed_files)
        self.assertIn("Makefile", result.changed_files)
        self.assertIn("README.repro-doctor.md", result.changed_files)


class SubprocessLifecycleTests(unittest.TestCase):
    def test_timeout_terminates_the_omnirush_process(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "app.py").write_text("print('ok')\n", encoding="utf-8")
            pid_file = root / "agent.pid"
            script = root / "fake-omnirush"
            script.write_text(
                f"#!{os.sys.executable}\n"
                "from pathlib import Path\n"
                "import os\n"
                "import time\n"
                f"Path({str(pid_file)!r}).write_text(str(os.getpid()))\n"
                "time.sleep(30)\n",
                encoding="utf-8",
            )
            script.chmod(script.stat().st_mode | stat.S_IXUSR)
            profile = detect_repository(root.parent)
            request = AgentRequest(
                role="stack-detector",
                root=root,
                profile=profile,
                prompt="test",
                timeout=0.2,
            )
            runner = OmniRushSubprocessRunner(binary=str(script))
            result = {}

            def invoke():
                try:
                    runner.run(request)
                except Exception as exc:
                    result["error"] = exc

            thread = threading.Thread(target=invoke)
            thread.start()
            for _ in range(100):
                if pid_file.exists():
                    break
                time.sleep(0.01)
            thread.join(timeout=2)

            self.assertFalse(thread.is_alive())
            self.assertIsInstance(result.get("error"), AgentTimeoutError)
            if pid_file.exists():
                pid = int(pid_file.read_text(encoding="utf-8"))
                for _ in range(100):
                    if not Path(f"/proc/{pid}").exists():
                        break
                    time.sleep(0.01)
                self.assertFalse(Path(f"/proc/{pid}").exists())
