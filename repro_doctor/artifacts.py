from __future__ import annotations

import re
from pathlib import Path

from .models import Artifact, PythonProfile


def _dockerfile(root: Path, profile: PythonProfile) -> str:
    requirements = next(
        (
            name
            for name in profile.dependency_files
            if name == "requirements.txt"
            or (name.startswith("requirements") and name.endswith(".txt"))
        ),
        None,
    )
    install_lines = []
    if requirements:
        install_lines.append(
            f"RUN python -m pip install --no-cache-dir -r {requirements}"
        )
    if any(name in profile.dependency_files for name in ("pyproject.toml", "setup.py", "setup.cfg")):
        install_lines.append("RUN python -m pip install --no-cache-dir .")
    lines = [
        f"FROM python:{profile.runtime}-slim",
        "",
        "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1",
        "WORKDIR /app",
        "COPY . .",
    ]
    if install_lines:
        lines.extend(["", *install_lines])
    lines.extend(["", 'CMD ["make", "test"]', ""])
    return "\n".join(lines)


def _makefile(profile: PythonProfile) -> str:
    return f".PHONY: test\n\ntest:\n\t{profile.test_command}\n"


def _append_test_target(existing: str, profile: PythonProfile) -> str:
    suffix = "" if existing.endswith("\n") else "\n"
    return (
        f"{existing}{suffix}\n# Added by repro-doctor.\n"
        f".PHONY: test\n\ntest:\n\t{profile.test_command}\n"
    )


def _dependency_proposal(root: Path, profile: PythonProfile) -> str:
    lines = [
        "# Repro-doctor dependency lock proposal.",
        "# Review each declaration and replace it with an exact version before release.",
    ]
    if not profile.dependency_files:
        lines.append("# No dependency metadata was found in the source repository.")
    else:
        for name in profile.dependency_files:
            lines.append(f"# Source metadata: {name}")
    return "\n".join(lines) + "\n"


def _readme(profile: PythonProfile, generated_paths: list[str]) -> str:
    package = profile.package_name or "(not declared)"
    dependencies = ", ".join(profile.dependency_files) or "none found"
    lockfile = profile.lockfile or "none; review requirements.repro-doctor.txt"
    generated = "\n".join(f"- `{path}`" for path in generated_paths)
    if "requirements.txt" in profile.dependency_files:
        setup_command = "python -m pip install -r requirements.txt"
    elif any(
        name in profile.dependency_files for name in ("pyproject.toml", "setup.py", "setup.cfg")
    ):
        setup_command = "python -m pip install ."
    else:
        setup_command = "Follow the repository's dependency instructions."
    return f"""# Reproducibility notes

Generated by `repro-doctor` from an isolated snapshot. The source repository
was not modified by generation.

## Detected project

- Stack: Python
- Package: {package}
- Runtime: Python {profile.runtime} ({profile.runtime_source})
- Dependency metadata: {dependencies}
- Usable lockfile: {lockfile}
- Test command: `{profile.test_command}`
- Detection confidence: {profile.confidence}

## Setup

```bash
{setup_command}
```

## Run

Use the repository's normal Python entry point or package command.

## Test

```bash
make test
```

## Docker

```bash
docker build -t repro-doctor-target .
docker run --rm repro-doctor-target
```

## Deploy

Cloud deployment is outside the Phase 1 scope. A deployable local container
can be built and run with the Docker commands above.

## Generated files

{generated}
"""


def generate_artifacts(root: Path, profile: PythonProfile) -> tuple[Artifact, ...]:
    """Create only reproducibility artifacts, preserving usable existing files."""

    artifacts: list[Artifact] = []
    if not (root / "Dockerfile").exists():
        artifacts.append(
            Artifact("Dockerfile", _dockerfile(root, profile), "add Python build image")
        )
    makefile = root / "Makefile"
    if not makefile.exists():
        artifacts.append(Artifact("Makefile", _makefile(profile), "add test entry point"))
    elif not re.search(r"^test\s*:", makefile.read_text(encoding="utf-8"), re.MULTILINE):
        artifacts.append(
            Artifact(
                "Makefile",
                _append_test_target(makefile.read_text(encoding="utf-8"), profile),
                "add missing test entry point",
            )
        )
    if not (root / ".python-version").exists() and not (root / "runtime.txt").exists():
        artifacts.append(Artifact(".python-version", f"{profile.runtime}\n", "pin Python runtime"))
    if profile.lockfile is None:
        artifacts.append(
            Artifact(
                "requirements.repro-doctor.txt",
                _dependency_proposal(root, profile),
                "document dependency pinning work",
            )
        )

    generated_paths = [artifact.path for artifact in artifacts]
    artifacts.append(
        Artifact(
            "README.repro-doctor.md",
            _readme(profile, generated_paths + ["README.repro-doctor.md"]),
            "document generated reproducibility contract",
        )
    )
    return tuple(artifacts)


def materialize(root: Path, artifacts: tuple[Artifact, ...]) -> None:
    for artifact in artifacts:
        destination = root / artifact.path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(artifact.content, encoding="utf-8")
